from pyvis.network import Network

# ---------------------------------------------------------
# 1. VERTICES
# ---------------------------------------------------------

vertices = {
    "A1": 6,
    "A2": 6,
    "A3": 6,
    "A4": 6,

    "B1": 5,
    "B2": 5,

    "C1": 4,
    "C2": 4,
    "C3": 4,
    "C4": 4,

    "D1": 3,
    "D2": 3,

    "E1": 2,
    "E2": 2,
}


# ---------------------------------------------------------
# 2. EDGES
# ---------------------------------------------------------

edges = [

    # A1
    ("A1", "C1"),
    ("A1", "C2"),
    ("A1", "C3"),
    ("A1", "C4"),
    ("A1", "D1"),
    ("A1", "D2"),

    # A4
    ("A4", "C1"),
    ("A4", "C2"),
    ("A4", "C3"),
    ("A4", "C4"),
    ("A4", "D1"),
    ("A4", "D2"),

    # A2
    ("A2", "B1"),
    ("A2", "B2"),
    ("A2", "C1"),
    ("A2", "C4"),
    ("A2", "E1"),
    ("A2", "E2"),

    # A3
    ("A3", "B1"),
    ("A3", "B2"),
    ("A3", "C1"),
    ("A3", "C4"),
    ("A3", "E1"),
    ("A3", "E2"),

    # B1
    ("B1", "C2"),
    ("B1", "C3"),
    ("B1", "D2"),

    # B2
    ("B2", "C2"),
    ("B2", "C3"),
    ("B2", "D1"),
]


# ---------------------------------------------------------
# 3. INITIAL POSITIONS
#
# You can change these if you want a different starting
# arrangement.
# ---------------------------------------------------------

positions = {
    "A1": (-600, -250),
    "A2": (-600, 250),
    "A3": (600, 250),
    "A4": (600, -250),

    "B1": (-300, 0),
    "B2": (300, 0),

    "C1": (-200, -400),
    "C2": (-200, 400),
    "C3": (200, 400),
    "C4": (200, -400),

    "D1": (-450, 500),
    "D2": (450, 500),

    "E1": (-450, -500),
    "E2": (450, -500),
}


# ---------------------------------------------------------
# 4. CREATE INTERACTIVE GRAPH
# ---------------------------------------------------------

net = Network(
    height="900px",
    width="100%",
    bgcolor="#ffffff",
    font_color="#000000",
    directed=False
)


# ---------------------------------------------------------
# 5. ADD VERTICES
# ---------------------------------------------------------

for vertex, degree in vertices.items():

    x, y = positions[vertex]

    net.add_node(
        vertex,
        label=f"{vertex}\nGrad {degree}",
        x=x,
        y=y,
        physics=False,
        size=25,
        title=f"{vertex}: Grad {degree}"
    )


# ---------------------------------------------------------
# 6. ADD EDGES
# ---------------------------------------------------------

for u, v in edges:
    net.add_edge(u, v)


# ---------------------------------------------------------
# 7. SETTINGS
# ---------------------------------------------------------

net.set_options("""
{
  "interaction": {
    "dragNodes": true,
    "dragView": true,
    "zoomView": true
  },

  "nodes": {
    "shape": "circle",
    "borderWidth": 2,
    "font": {
      "size": 18
    }
  },

  "edges": {
    "width": 2,
    "smooth": false
  },

  "physics": {
    "enabled": false
  }
}
""")


# ---------------------------------------------------------
# 8. CREATE HTML FILE
# ---------------------------------------------------------

net.write_html("graph.html")

print("Graph created!")
print("Open graph.html in your browser.")